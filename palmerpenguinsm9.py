#Import the math module
import math

# Create a Penguin Class at the module level
class Penguin:
    def __init__(self, sample_number, species, body_mass):
        self.sample_number = sample_number
        self.species = species
        self.body_mass = body_mass
    def display_info(self):
        print(f"Sample Number: {self.sample_number}")
        print(f"Species: {self.species}")
        print(f"Body Mass: {self.body_mass} grams")

# constants representing the species and count
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

# add constants for the number of penguins
NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

# Define functions
def calculate_percentage(count, total):
    percentage = count / total * 100
    return percentage
# Function to classify by percentage
def classify_species(percent):
    if percent < 25:
        return "small"
    elif percent < 40:
        return "medium"
    else:
        return "large"
# Determine Relative Position
def get_position_description(selected_species, largest_species, smallest_species):
    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle-sized"
# Function to display species stats
def display_species_statistics(names, counts, percentages):
    for index, species in enumerate(names):
        print(f"{species}: {counts[index]} "
              f"({percentages[index]:.2f}%)")

# Function to display the Penguin Observation
def display_penguin_observation(sample_number, species, bill_length,
                                bill_depth, body_mass, sex):
    print("\nSample Penguin Observation")
    print(f"{'Sample Number:':<18}{sample_number}")
    print(f"{'Species:':<18}{species}")
    print(f"{'Bill length:':<18}{bill_length} mm")
    print(f"{'Bill depth:':<18}{bill_depth} mm")
    print(f"{'Body mass:':<18}{body_mass} g")
    print(f"{'Sex:':<18}{sex}")


